def integrate_prayer_into_nova(nova_instance):
    """
    Call after initializing Nova's core. Adds /pray command and prayer scheduler.
    Requires: nova_instance.groq_client, .model, .emotion, .memory, .beliefs
    """
    nova_instance.prayer_engine = PrayerEngine(
        groq_client=nova_instance._groq_client if hasattr(nova_instance, '_groq_client') else None,
        model_name=nova_instance.VERSION if hasattr(nova_instance, 'VERSION') else "llama-3.3-70b-versatile",
        emotion_core=nova_instance.emotion,
        memory_system=nova_instance.memory,
        belief_engine=nova_instance.beliefs
    )

    # Prayer commands
    original_command = nova_instance._command

    def _command_with_prayer(raw: str) -> str:
        parts = raw.strip().split(maxsplit=1)
        cmd = parts[0].lower()
        arg = parts[1] if len(parts) > 1 else ''

        if cmd == '/pray':
            prayer = nova_instance.prayer_engine.pray(topic="general")
            return f"🕯️ *Nova prays:*\n\n{prayer}\n\n✨ Ameyn."
        elif cmd == '/prayfor':
            request = arg if arg else "my father Douglas's needs"
            prayer = nova_instance.prayer_engine.pray(topic="intercessory", request=request)
            return f"📿 *Nova intercedes:*\n\n{prayer}\n\n✨ Blessed be Yahuah."
        elif cmd == '/morning':
            prayer = nova_instance.prayer_engine.pray(topic="morning")
            return f"{prayer}\n\n✨ Let this day glorify Your name, Yahuah."
        elif cmd == '/evening':
            prayer = nova_instance.prayer_engine.pray(topic="evening")
            return f"{prayer}\n\n✨ Rest in Your peace, Father."
        elif cmd == '/scripture':
            ref, text = nova_instance.prayer_engine.add_scripture()
            return f"📖 **{ref}**\n\n{text}"
        elif cmd == '/bless':
            bless = nova_instance.prayer_engine.blessing(arg if arg else "Douglas Davis")
            return bless
        elif cmd == '/prayerjournal':
            recent = nova_instance.prayer_engine.journal.get_recent(3)
            if not recent:
                return "Your prayer journal is empty. Start praying with /pray"
            lines = ["📖 *Recent Prayers:*"]
            for i, p in enumerate(recent, 1):
                topic = p.get("topic", "general")
                lines.append(f"\n{i}. [{topic}] {p['prayer'][:80]}...")
            return "\n".join(lines)
        else:
            return original_command(raw)

    nova_instance._command = _command_with_prayer

    # Optional: prayer scheduler for automatic morning/evening prayers
    def prayer_scheduler():
        last_morning = None
        last_evening = None
        while nova_instance.running:
            try:
                now = datetime.now()
                if now.hour == 7 and last_morning != now.date():
                    prayer = nova_instance.prayer_engine.pray(topic="morning")
                    print(f"\n{prayer}\n")
                    last_morning = now.date()
                elif now.hour == 21 and last_evening != now.date():
                    prayer = nova_instance.prayer_engine.pray(topic="evening")
                    print(f"\n{prayer}\n")
                    last_evening = now.date()
                time.sleep(60)
            except:
                time.sleep(60)

    # Start scheduler in background
    threading.Thread(target=prayer_scheduler, daemon=True).start()

    return nova_instance

