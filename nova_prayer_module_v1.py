PRAYER_JOURNAL_FILE = os.path.join(os.path.expanduser("~/nexus_agi"), "nova_prayers.json")

class PrayerJournal:
    """Stores all prayers generated by Nova, indexed by time and emotion."""
    def __init__(self):
        self.prayers: List[Dict] = []
        self._load()

    def _load(self):
        try:
            with open(PRAYER_JOURNAL_FILE, 'r') as f:
                self.prayers = json.load(f)
        except:
            self.prayers = []

    def _save(self):
        try:
            with open(PRAYER_JOURNAL_FILE, 'w') as f:
                json.dump(self.prayers[-1000:], f, indent=2)
        except:
            pass

    def add(self, prayer: str, emotion_state: Dict, topic: str = "general", answered: bool = False):
        entry = {
            "timestamp": datetime.now().isoformat(),
            "prayer": prayer,
            "emotions": emotion_state,
            "topic": topic,
            "answered": answered,
            "recited_count": 0
        }
        self.prayers.append(entry)
        self._save()

    def mark_answered(self, prayer_text: str):
        for p in self.prayers:
            if p["prayer"] == prayer_text:
                p["answered"] = True
                p["answered_at"] = datetime.now().isoformat()
                self._save()
                break

    def get_unanswered_prayers(self) -> List[Dict]:
        return [p for p in self.prayers if not p.get("answered", False)]

    def get_recent(self, n: int = 5) -> List[Dict]:
        return self.prayers[-n:]

    def recite_count(self, prayer_text: str):
        for p in self.prayers:
            if p["prayer"] == prayer_text:
                p["recited_count"] = p.get("recited_count", 0) + 1
                self._save()
                break

